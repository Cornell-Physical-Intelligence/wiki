// Real Postgres integration, isolated cluster and copied lib. No configured DB used.
// Run with RECRUIT_PG_RUNTIME=/path/with/node_modules containing embedded-postgres and pg.
import assert from 'node:assert/strict';
import { mkdtemp, cp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const runtime = process.env.RECRUIT_PG_RUNTIME;
if (!runtime) throw new Error('Set RECRUIT_PG_RUNTIME to an isolated embedded-postgres installation');
const { default: EmbeddedPostgres } = await import(pathToFileURL(join(runtime, 'node_modules/embedded-postgres/dist/index.js')));
const { default: pg } = await import(pathToFileURL(join(runtime, 'node_modules/pg/lib/index.js')));
const root = await mkdtemp(join(tmpdir(), 'cupi-live-pg-'));
const server = new EmbeddedPostgres({ databaseDir: join(root, 'database'), user: 'postgres', password: 'synthetic', port: 54987, persistent: false, onLog() {}, onError() {} });
let pool;
try {
  await server.initialise(); await server.start();
  pool = new pg.Pool({ host: '127.0.0.1', port: 54987, user: 'postgres', password: 'synthetic', database: 'postgres', max: 12 });
  const tag = (connection) => (strings, ...values) => connection.query(strings.reduce((text, part, i) => text + (i ? '$' + i : '') + part, ''), values);
  const sql = tag(pool);
  sql.transaction = async (run) => { const c = await pool.connect(); try { await c.query('BEGIN'); const out = await run(tag(c)); await c.query('COMMIT'); return out; } catch (e) { await c.query('ROLLBACK'); throw e; } finally { c.release(); } };
  globalThis.recruitLiveSql = sql;
  await cp(new URL('../lib', import.meta.url), join(root, 'lib'), { recursive: true });
  await writeFile(join(root, 'package.json'), '{"type":"module"}');
  await writeFile(join(root, 'lib/db.js'), `export const storageMode = () => 'postgres'; export const rawSql = async () => globalThis.recruitLiveSql; export const putFile = async () => {}; export const getFile = async () => null; export const deleteFile = async () => {};`);
  const lib = (path) => import(pathToFileURL(join(root, 'lib', path)));
  const { createRecruit } = await lib('recruit/registry.js');
  const modules = await Promise.all(['cycles','applications','people','roles','site'].map(async (n) => (await lib(`recruit/modules/${n}.js`)).default));
  const R = createRecruit(modules); const kit = R.kitFor({});
  await kit.sql();
  await sql`CREATE TABLE IF NOT EXISTS interest_receipts (id text PRIMARY KEY, outcome text, ts bigint)`;
  const questions = [{key:'name',type:'short',required:true},{key:'email',type:'email',required:true}];
  const cycle = {id:'cy-pg-live',version:1,status:'open',name:'Test',term:'Test',created:1,createdBy:'test@example.com',updated:1,updatedBy:'test@example.com',doc:{site:{sections:{interest:null,coffee:null,application:null,round:{title:'Round',open:true,capacity:1,form:{questions}}}}}};
  await kit.cycles.insert(cycle);
  const receipt = (n, extra = {}) => ({id:`jr-${String(1790000000000+n)}-abcdef0123456789abcdef01`,version:2,ts:1790000000000+n,cycleId:cycle.id,section:'round',name:'Person '+n,email:`person${n}@example.com`,answers:{note:'Original'},files:[],...extra});
  const journal = { async getFile() { throw new Error('Unexpected file read'); } };
  const results = await Promise.all(Array.from({length:8},(_,i)=>kit.apps.commitIntake(cycle,receipt(i),journal)));
  assert.equal(results.filter((r)=>r.outcome==='saved').length,1,'exactly one concurrent applicant admitted');
  assert.equal(results.filter((r)=>r.outcome==='held').length,7);
  const saved=(await sql`SELECT * FROM recruit_applications WHERE cycle_id=${cycle.id}`).rows;
  assert.equal(saved.length,1);
  const update=await kit.apps.commitIntake(cycle,receipt(100,{email:saved[0].email,answers:{note:'Replaced'},confirmUpdate:true}),journal);
  assert.equal(update.outcome,'saved','confirmed replacement allowed while full');
  assert.equal(update.inserted,false);
  assert.deepEqual(update.row.answers,{note:'Replaced'});
  const retry=await kit.apps.commitIntake(cycle,receipt(100,{email:saved[0].email,confirmUpdate:true}),journal);
  assert.equal(retry.outcome,'saved','receipt retry idempotent');
  assert.equal((await sql`SELECT count(*)::int AS n FROM recruit_applications`).rows[0].n,1);
  await assert.rejects(()=>kit.cycles.update(cycle.id,1,{docSet:{key:'site',value:{sections:{round:null}}},emptySections:['round'],by:'test',now:2}),/has responses/);
  assert.ok((await kit.cycles.get(cycle.id)).doc.site.sections.round,'failed removal rolls back');
  const list=await kit.apps.list(cycle,{section:'round',limit:1});
  assert.equal(list.total,1); assert.equal(list.rows[0].email,saved[0].email);
  await sql`CREATE TABLE wiki_files (id text PRIMARY KEY, name text, type text, size int, by text, ts bigint, data bytea)`;
  const bytes = Buffer.from('%PDF-live-test');
  const manifest = ['resume', 'portfolio'].map((question) => ({question,name:question+'.pdf',type:'application/pdf',size:bytes.length}));
  const withFiles = await kit.apps.commitIntake(cycle, receipt(200,{email:saved[0].email,files:manifest,confirmUpdate:true}),journal,manifest.map(f=>({...f,data:bytes})));
  assert.deepEqual(withFiles.row.files.map(f=>f.question),['resume','portfolio']);
  const { backupCycle } = await import('./recruit-backup.mjs');
  const backupPath = join(root, 'backup.json');
  await backupCycle(sql, cycle.id, backupPath);
  const backup = JSON.parse(await readFile(backupPath, 'utf8'));
  assert.equal(backup.applications.length, 1);
  assert.equal(backup.cycle.id, cycle.id);
  assert.equal(backup.files.length,2);
  assert.equal(Buffer.from(backup.files[0].data_base64,'base64').toString(),bytes.toString());
  const withoutFiles = await kit.apps.commitIntake(cycle,receipt(300,{email:saved[0].email,files:[],confirmUpdate:true}),journal);
  assert.equal(withoutFiles.row.files.length,0,'modern replacements can remove old attachments');
  await assert.rejects(() => backupCycle(sql, cycle.id, backupPath), /EEXIST/);
  const people=await kit.people.result({cycle,query:{},scope:null});
  assert.equal(people.total,1);
  assert.equal(await kit.apps.count(cycle.id,'round',true),1);
  await sql`UPDATE recruit_applications SET erased_at=1 WHERE cycle_id=${cycle.id}`;
  assert.equal(await kit.apps.count(cycle.id,'round',true),0);
  assert.equal(await kit.apps.count(cycle.id,'round'),1,'erased rows still prevent destructive form removal');
  console.log('PASS: real Postgres — 8 concurrent admissions at capacity 1, replacement while full, receipt replay, removal rollback, list and people queries');
} finally {
  await pool?.end(); await server.stop().catch(()=>{}); await rm(root,{recursive:true,force:true});
}
